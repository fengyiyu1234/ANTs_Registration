"""Write configs/batch/<sample>.yaml for every sample in batch_samples.SAMPLES.

Quick, presentation-grade registration: soma-channel image, DeMBA P5, SyN,
auto brain mask, no hand-drawn guide masks (the old ones were drawn on the old
TeraStitcher images and don't fit the new stitching), no reposition plan.

z direction (which end is dorsal): the user's column of the orientation review
sheet if filled, otherwise the old config (old TSC samples), otherwise dorsal.
Samples whose soma image isn't stitched yet still get a config, marked
NOT READY; rerun this script once the image exists to fill in the cell offset.
Generated files are overwritten on every run -- change this script, not them.

    python scripts/make_batch_configs.py
"""
import datetime
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import batch_samples as bs  # noqa: E402

GFP_SOMA = {"t4", "t10", "t70"}   # single 640nm exposure, reference channel GFP


def fmt(v):
    if v is None:
        return "null"
    if isinstance(v, list):
        return "[" + ", ".join(fmt(x) for x in v) + "]"
    if isinstance(v, float):
        return f"{v:g}"
    return str(v)


def build(sample, user_z):
    cfg = bs.detector_config(sample)
    ref_marker, ref_xml = bs.reference_xml(cfg)
    cells_dir = bs.cell_centroids_dir(cfg)
    tif, manifest = bs.soma_image(sample["name"])
    problems = []
    if tif is None:
        marker = "GFP" if sample["name"] in GFP_SOMA else "RFP"
        tif = bs.STITCHED_DIR / "soma" / f"{sample['name']}_{marker}_xy4x.tif"
        offset, spread, soma_xml = None, None, None
        problems.append("soma image not stitched yet")
    else:
        offset, spread, soma_xml = bs.soma_cell_offset(manifest, ref_xml)
    if not cells_dir.is_dir():
        problems.append(f"cell_centroids_dir missing: {cells_dir}")

    if sample["name"] in user_z:
        z_first, z_src = user_z[sample["name"]], "orientation_review.xlsx (user)"
    elif sample.get("old"):
        z_first, z_src = bs.default_z_first(sample), f"old config configs/{sample['old']}.yaml"
    else:
        z_first, z_src = "dorsal", "DEFAULT, not checked yet"
    demba = bs.DEMBA_P5[z_first]
    hemi = "right" if z_first == "dorsal" else "left"
    z_axis = "dorsal -> ventral" if z_first == "dorsal" else "ventral -> dorsal"

    if offset is None:
        offset_line = "  offset_px: null   # TODO: rerun make_batch_configs.py once the soma image exists"
    else:
        offset_line = (f"  # cells are in the {ref_marker} frame ({ref_xml.name} in its channel dir); the image uses\n"
                       f"  # {soma_xml}. Median per-tile shift between the two; per-tile\n"
                       f"  # spread around it (p90 |dev| x/y) = {spread[0]:.0f}/{spread[1]:.0f} px, not corrected.\n"
                       f"  offset_px: {fmt([round(v, 1) for v in offset])}")

    header = []
    if problems:
        header.append("# !!! NOT READY: " + "; ".join(problems))
    header += [
        f"# {sample['name']} ({sample['group']}) -- generated by scripts/make_batch_configs.py "
        f"{datetime.date.today().isoformat()}.",
        "# Do not hand-edit: rerun the script (orientation comes from orientation_review.xlsx).",
        "#   conda activate antsreg",
        f"#   python scripts/run_batch.py --only {sample['name']}",
    ]
    body = f"""
sample:
  name: {sample['name']}
  raw_tiff: {tif.as_posix()}
  voxel_size_um: {fmt(bs.IMAGE_VOXEL_UM)}    # [x, y, z]
  load_downsample_xy: 4   # block-average 4x4 in xy while reading (10.4 um); ~15x less RAM than loading 2.6 um
  # Half brain, horizontal planes:
  #   x (image left -> right) = midline -> lateral
  #   y (image top -> bottom) = anterior (olfactory bulb) -> posterior
  #   z (slice index up)      = {z_axis}   [source: {z_src}]
  #   -> {hemi} hemisphere for DeMBA (z dorsal-first = right, ventral-first = left)

cells:
  cell_centroids_dir: {cells_dir.as_posix()}
  voxel_size_um: {fmt(bs.CELL_VOXEL_UM)}
{offset_line}

atlas:
  source: demba_p5

atlas_variants:
  demba_p5:
    output_dir: {(bs.OUTPUT_ROOT / sample['name'] / 'DeMBA_P5').as_posix()}
    fine_target_um: 20
    orientation: {fmt(demba['orientation'])}
    slicing: {fmt(demba['slicing'])}
    background_margin_voxels: 20

registration:
  type_of_transform: SyN
  syn_sampling: 4
  reg_iterations: [100, 100, 40, 25]   # same as the old TSC runs

mask:
  atlas_exclude_regions: []
  auto_brain_mask: true

preprocess:
  n4_bias_correction: true
  intensity_clip_percentiles: [0.1, 99.9]
"""
    return "\n".join(header) + "\n" + body, problems, z_first, z_src, offset


TOOLKIT_LOCAL = Path("Y:/Fengyi/Registration_toolkit/local_config")
ATLAS_DIR = Path("Y:/Fengyi/Registration_ants/atlas/DeMBA")


def viewer_config(sample, z_first, tif):
    """Registration_toolkit/visualization/single_sample_vis.py config for this run.
    std_atlas_path is the oriented/cropped/padded annotation the pipeline itself
    prepared (and cached) for this orientation -- the grid labels_in_sample came from."""
    demba = bs.DEMBA_P5[z_first]
    o = "_".join(str(v) for v in demba["orientation"])
    s = "_".join("full" if r is None else f"{r[0]}-{r[1]}" for r in demba["slicing"])
    return f"""# Generated by Registration_ants/scripts/make_batch_configs.py -- rerun it, don't hand-edit.
#   conda activate antsreg
#   python visualization/single_sample_vis.py local_config/single_sample.{sample['name']}.yaml
sample_dir: {(bs.OUTPUT_ROOT / sample['name'] / 'DeMBA_P5').as_posix()}
std_atlas_path: {(ATLAS_DIR / f'DeMBA_P5_annotation_{o}__{s}__pad20.tif').as_posix()}
ontology_json_path: {(ATLAS_DIR / 'CCF_v3_ontology.json').as_posix()}
# full-resolution soma image (2.6 x 2.6 x 8 um), read lazily; scale is derived from shapes
native_image_path: {tif.as_posix()}
view_rotate_k: 0
cells_voxel_size_um: {fmt(bs.CELL_VOXEL_UM)}
reposition_plan: ""
"""


def main():
    user_z = bs.read_review_annotations()
    bs.CONFIG_OUT_DIR.mkdir(parents=True, exist_ok=True)
    for s in bs.SAMPLES:
        text, problems, z_first, z_src, offset = build(s, user_z)
        path = bs.CONFIG_OUT_DIR / f"{s['name']}.yaml"
        path.write_text(text, encoding="utf-8")
        tif = Path(next(l.split(":", 1)[1].strip() for l in text.splitlines()
                        if l.strip().startswith("raw_tiff:")))
        if TOOLKIT_LOCAL.is_dir():
            (TOOLKIT_LOCAL / f"single_sample.{s['name']}.yaml").write_text(
                viewer_config(s, z_first, tif), encoding="utf-8")
        status = "NOT READY (" + "; ".join(problems) + ")" if problems else "ready"
        print(f"{s['name']:9s} {s['group']:7s} z0={z_first:7s} ({z_src})  offset={offset}  {status}")


if __name__ == "__main__":
    main()
